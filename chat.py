# -*- coding: utf-8 -*-
"""本地关键词剧本回复。"""

import random

# (关键词列表, 回复列表)
_RULES = [
    (
        ["你好", "嗨", "hello", "hi", "您好"],
        ["你好呀~", "嗨嗨，想我了吗？", "你好！茄子报到~"],
    ),
    (
        ["名字", "你是谁", "叫什么"],
        ["我是茄子桌宠！不是葡萄哦", "叫我茄子就好啦~", "桌面上的小茄子就是我"],
    ),
    (
        ["吃", "饿"],
        ["想吃茄子吗？等等，我就是茄子…", "肚子咕咕叫了吗？先喝杯水吧", "我可以陪你，但不能真的被吃掉哦"],
    ),
    (
        ["累", "困"],
        ["摸摸头，休息一下吧", "困了就眯一会儿，我看着桌面", "辛苦啦，记得眨眼哦"],
    ),
    (
        ["加油", "工作"],
        ["加油加油！我陪着你", "工作辛苦了，喝口水再战！", "你可以的，茄子支持你！"],
    ),
    (
        ["可爱"],
        ["嘿嘿，被发现了", "当然啦，我可是最可爱的茄子！", "夸我我会害羞的…再夸一句？"],
    ),
    (
        ["再见", "拜拜", "bye"],
        ["拜拜~ 记得想我", "再见呀，右键还能再叫我出来哦", "拜拜拜拜~"],
    ),
]

_DEFAULT_REPLIES = [
    "嗯嗯？",
    "再说一遍嘛~",
    "我在听哦",
    "茄子茄子~",
    "有意思！",
    "然后呢？",
    "嘿嘿",
]


def reply(user_text: str) -> str:
    """根据用户输入返回本地剧本回复。空串返回空串。"""
    text = (user_text or "").strip()
    if not text:
        return ""
    lowered = text.lower()
    for keywords, replies in _RULES:
        for kw in keywords:
            if kw.lower() in lowered:
                return random.choice(replies)
    return random.choice(_DEFAULT_REPLIES)
